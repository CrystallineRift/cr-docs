#!/usr/bin/env python3
"""Generate docs/content/02-world-fill.md from the cr-api-unity packet JSON.
Usage: python3 -I scripts/gen-world-fill.py <cr-api-unity root> <plan-sections.md> <out.md>
Quest key/name/giver/giver name from Side/*.json; kind + level band from the plan's quest tables;
dungeon rows from Data/Dungeons/*.json (no _example); framing quest from the plan."""
import glob, json, os, re, sys

root, plan_path, out = sys.argv[1:4]
game = os.path.join(root, "Assets/CR/Game")
plan = open(plan_path, encoding="utf-8").read().split("\n")

# plan quest rows: | # | quest-key | region . Lvl | kind | giver | ...
plan_rows = {}
for ln in plan:
    c = [x.strip() for x in ln.split("|")]
    if len(c) > 5 and c[2].startswith("quest-"):
        m = re.search(r"L(\d+)(?:-(\d+))?", c[3])
        band = "L%s-%s" % (m.group(1), m.group(2)) if m and m.group(2) else ("L" + m.group(1) if m else "")
        plan_rows[c[2]] = (band, c[4])

# framing quests per dungeon, in plan order: header line then next 'Framing quest:' line
framing, cur = {}, None
for ln in plan:
    if ln.startswith("**Dungeon"):
        cur = ln
    m = re.match(r"Framing quest: (quest-[a-z0-9-]+)", ln)
    if m and cur:
        framing[cur] = m.group(1)
        cur = None

dungeons = []
for f in sorted(glob.glob(os.path.join(game, "OpenWorld/Data/Dungeons/*.json"))):
    if os.path.basename(f).startswith("_"):
        continue
    d = json.load(open(f, encoding="utf-8"))
    hdr = [h for h in framing if d["key"] in h or d["name"].lower() in h.lower()]
    dungeons.append((d, framing[hdr[0]] if hdr else ""))
dng_of = {q: d["key"] for d, q in dungeons if q}

def one_line(s):
    s = re.split(r"(?<=[.;])\s", s.strip())[0]
    return s if len(s) <= 150 else s[:147].rstrip() + "..."

def esc(s): return str(s).replace("|", "\\|")
lines = ["# World Fill Content", "",
 "Side quests, optional dungeons, zones and pickups added by the world-fill program. All text is AI draft (see the [AI Content Ledger](?page=content/01-ai-content-ledger)). The packet schema and lint are in [Side Content Packets](?page=unity/46-side-content-packets); the dungeon spec in [Dungeon Scaffold](?page=unity/47-dungeon-scaffold).", "",
 "Generated by `scripts/gen-world-fill.py` from `Assets/CR/Game/Story/Content/Side/*.json` and `Assets/CR/Game/OpenWorld/Data/Dungeons/*.json`. Do not edit the tables by hand.", ""]
total = 0
for f in sorted(glob.glob(os.path.join(game, "Story/Content/Side/*.json"))):
    if f.endswith("side-ledger.json"):
        continue
    p = json.load(open(f, encoding="utf-8"))
    npcs = {n["key"]: n.get("name", n["key"]) for n in p.get("npcs", [])}
    lines += ["## Packet %s (%d quests)" % (p["packet"], len(p["quests"])), "",
              "| Quest key | Name | Giver | Kind | Level band | Dungeon |", "|---|---|---|---|---|---|"]
    for q in p["quests"]:
        band, kind = plan_rows.get(q["key"], ("", ""))
        g = npcs.get(q["giverNpc"], q["giverNpc"])
        lines.append("| `%s` | %s | %s | %s | %s | %s |" % (q["key"], esc(q["name"]), esc(g), esc(kind), band,
                     ("`%s`" % dng_of[q["key"]]) if q["key"] in dng_of else ""))
    total += len(p["quests"])
    lines.append("")
lines += ["## Dungeons (%d)" % len(dungeons), "",
          "| Key | Name | Region | Framing quest | Gimmick |", "|---|---|---|---|---|"]
for d, q in dungeons:
    lines.append("| `%s` | %s | %s | %s | %s |" % (d["key"], esc(d["name"]), d["region"], ("`%s`" % q) if q else "", esc(one_line(d["gimmick"]))))
lines += ["", "Total side quests: %d." % total, ""]
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(total, len(dungeons), sum(1 for d, q in dungeons if not q))
